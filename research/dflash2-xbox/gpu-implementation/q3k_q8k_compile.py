"""Compile the isolated DFlash Q8_K prepack and Q3_K x Q8_K dot shaders."""

from __future__ import annotations

import argparse
import hashlib
import shutil
import subprocess
import tempfile
from pathlib import Path


ROOT = Path(__file__).resolve().parents[3]
SOURCES = ROOT / "shaders" / "dflash"
OUTPUT = ROOT / "shaders" / "generated" / "dflash_q3k_q8k_dxil.h"
KERNELS = (
    ("q8k_quantize.hlsl", "CSQuantize", "kDflashQ8kQuantizeDxil", ()),
    ("q8k_quantize.hlsl", "CSQuantize", "kDflashQ8kQuantizeExactDxil",
     ("-D", "DFLASH_Q8_EXACT_SCALE_FP64=1")),
    ("q3k_q8k_matmul.hlsl", "CSDot", "kDflashQ3kQ8kDotDxil", ()),
)


def find_dxc(explicit: str | None) -> str:
    if explicit:
        return explicit
    found = shutil.which("dxc") or shutil.which("dxc.exe")
    if found:
        return found
    sdk = Path(r"C:\Program Files (x86)\Windows Kits\10\bin\10.0.26100.0\x64\dxc.exe")
    if sdk.is_file():
        return str(sdk)
    raise SystemExit("dxc not found; pass --dxc")


def compile_kernel(dxc: str, source: str, entry: str, extra_flags: tuple[str, ...]) -> bytes:
    with tempfile.TemporaryDirectory() as temporary:
        binary = Path(temporary) / "kernel.dxil"
        subprocess.run(
            [dxc, "-T", "cs_6_0", "-E", entry, "-O3", "-WX", *extra_flags,
             "-Fo", str(binary),
             str(SOURCES / source)],
            check=True,
        )
        return binary.read_bytes()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dxc", help="path to dxc.exe")
    args = parser.parse_args()
    dxc = find_dxc(args.dxc)
    lines = [
        "// AUTO-GENERATED by q3k_q8k_compile.py; do not edit.",
        "#pragma once",
        "#include <cstddef>",
        "#include <cstdint>",
        "// clang-format off",
    ]
    for source, entry, symbol, extra_flags in KERNELS:
        data = compile_kernel(dxc, source, entry, extra_flags)
        digest = hashlib.sha256(data).hexdigest()
        lines.extend([
            f"// {source} {entry} {' '.join(extra_flags)}, cs_6_0, "
            f"{len(data)} bytes, sha256 {digest}",
            f"static const uint8_t {symbol}[] = {{",
        ])
        for offset in range(0, len(data), 12):
            lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in data[offset:offset + 12]) + ",")
        lines.extend(["};", f"static const size_t {symbol}Size = {len(data)};"])
        print(f"{symbol}: {len(data)} bytes sha256={digest}")
    lines.append("// clang-format on")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(OUTPUT)


if __name__ == "__main__":
    main()
