"""Compile SYNC-only HLSL entry points into one C++ DXIL header."""

import shutil
import subprocess
import tempfile
from pathlib import Path


ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / "shaders" / "dflash" / "sync_ops.hlsl"
OUTPUT = ROOT / "shaders" / "generated" / "dflash_sync_ops_dxil.h"


def main():
    compiler = shutil.which("dxc.exe") or Path(
        r"C:\Program Files (x86)\Windows Kits\10\bin\10.0.26100.0\x64\dxc.exe"
    )
    if not Path(compiler).is_file():
        raise SystemExit("dxc.exe not found")
    entries = {
        "F32Matmul": "kDflashSyncF32MatmulDxil",
        "FcNorm": "kDflashSyncFcNormDxil",
        "KeyNormRope": "kDflashSyncKeyNormRopeDxil",
        "ScaleRows": "kDflashSyncScaleRowsDxil",
    }
    lines = [
        "// AUTO-GENERATED by gpu-implementation/sync_compile.py; do not edit.",
        "#pragma once",
        "#include <cstddef>",
        "#include <cstdint>",
    ]
    with tempfile.TemporaryDirectory() as temporary:
        for entry, symbol in entries.items():
            dxil = Path(temporary) / f"{entry}.dxil"
            subprocess.run(
                [str(compiler), "-T", "cs_6_0", "-E", entry, "-O3", "-Fo", str(dxil), str(SOURCE)],
                check=True,
            )
            data = dxil.read_bytes()
            lines.append(f"// {entry}: {len(data)} DXIL bytes")
            lines.append(f"static const uint8_t {symbol}[] = {{")
            for index in range(0, len(data), 12):
                lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in data[index:index + 12]) + ",")
            lines.extend(["};", f"static const size_t {symbol}Size = {len(data)};"])
            print(f"{entry}: {len(data)} DXIL bytes")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(OUTPUT)


if __name__ == "__main__":
    main()
