"""Compile DRAFT Q4_K/Q5_K x GGML Q8_K HLSL variants."""

import shutil
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / "shaders/dflash/dflash_draft_quant_q8.hlsl"
OUTPUT = ROOT / "shaders/generated/dflash_draft_quant_q8_dxil.h"


def main():
    compiler = shutil.which("dxc.exe") or Path(
        r"C:\Program Files (x86)\Windows Kits\10\bin\10.0.26100.0\x64\dxc.exe"
    )
    if not Path(compiler).is_file():
        raise SystemExit("dxc.exe not found")
    lines = ["// AUTO-GENERATED by draft_compile_quant_q8.py; do not edit.",
             "#pragma once", "#include <cstddef>", "#include <cstdint>"]
    with tempfile.TemporaryDirectory() as directory:
        for kind in ("Q4", "Q5"):
            symbol = f"kDflashDraft{kind}kQ8kDotDxil"
            path = Path(directory) / f"{kind}.dxil"
            subprocess.run([str(compiler), "-T", "cs_6_0", "-E", "CSDot",
                            "-D", f"DFLASH_{kind}_K=1", "-O3", "-WX", "-Fo",
                            str(path), str(SOURCE)], check=True)
            data = path.read_bytes()
            lines.append(f"static const uint8_t {symbol}[] = {{")
            for index in range(0, len(data), 12):
                lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in data[index:index + 12]) + ",")
            lines.extend(["};", f"static const size_t {symbol}Size = {len(data)};"])
            print(f"{kind}_K x Q8_K: {len(data)} bytes")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(OUTPUT)


if __name__ == "__main__":
    main()
