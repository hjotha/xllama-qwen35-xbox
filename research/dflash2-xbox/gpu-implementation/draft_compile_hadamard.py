"""Compile the shared DFlash2 H64/H128 attention rotation to AOT DXIL."""

import shutil
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / "shaders/dflash/dflash_hadamard128.hlsl"
OUTPUT = ROOT / "shaders/generated/dflash_hadamard128_dxil.h"


def main():
    compiler = shutil.which("dxc.exe") or Path(
        r"C:\Program Files (x86)\Windows Kits\10\bin\10.0.26100.0\x64\dxc.exe"
    )
    if not Path(compiler).is_file():
        raise SystemExit("dxc.exe not found")
    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory) / "hadamard.dxil"
        subprocess.run(
            [str(compiler), "-T", "cs_6_0", "-E", "CSHadamard", "-O3", "-WX",
             "-Fo", str(path), str(SOURCE)], check=True,
        )
        data = path.read_bytes()
    lines = [
        "// AUTO-GENERATED by draft_compile_hadamard.py; do not edit.",
        "#pragma once", "#include <cstddef>", "#include <cstdint>",
        "static const uint8_t kDflashHadamard128Dxil[] = {",
    ]
    for index in range(0, len(data), 12):
        lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in data[index:index + 12]) + ",")
    lines.extend(["};", f"static const size_t kDflashHadamard128DxilSize = {len(data)};"])
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Hadamard H64/H128: {len(data)} bytes -> {OUTPUT}")


if __name__ == "__main__":
    main()
