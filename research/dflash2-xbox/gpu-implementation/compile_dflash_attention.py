"""Compile the isolated DFlash2 attention shader to an AOT DXIL header."""

from __future__ import annotations

import os
import shutil
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / "shaders/dflash/dflash_attention.hlsl"
HEADER = ROOT / "shaders/generated/dflash_attention_dxil.h"
SYMBOL = "kDflashAttentionDxil"


def compiler() -> str:
    explicit = os.environ.get("DXC")
    if explicit:
        return explicit
    found = shutil.which("dxc") or shutil.which("dxc.exe")
    if found:
        return found
    sdk = Path(r"C:\Program Files (x86)\Windows Kits\10\bin\10.0.26100.0\x64\dxc.exe")
    if sdk.is_file():
        return str(sdk)
    raise SystemExit("dxc not found; set DXC to the compiler path")


def main() -> None:
    with tempfile.TemporaryDirectory() as directory:
        dxil = Path(directory) / "dflash_attention.dxil"
        subprocess.run([compiler(), "-T", "cs_6_0", "-E", "CSMain", "-O3", "-WX",
                        "-Fo", str(dxil), str(SOURCE)], check=True)
        data = dxil.read_bytes()
    lines = [
        "// AUTO-GENERATED by research/dflash2-xbox/gpu-implementation/compile_dflash_attention.py; do not edit.",
        "// Source: shaders/dflash/dflash_attention.hlsl (cs_6_0 CSMain -O3 -WX)",
        "#pragma once",
        "#include <cstddef>",
        "#include <cstdint>",
        f"// {len(data)} bytes DXIL",
        "// clang-format off",
        f"static const uint8_t {SYMBOL}[] = {{",
    ]
    for index in range(0, len(data), 12):
        lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in data[index:index + 12]) + ",")
    lines += ["};", f"static const size_t {SYMBOL}Size = {len(data)};", "// clang-format on"]
    HEADER.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{HEADER}: {len(data)} bytes")


if __name__ == "__main__":
    main()
