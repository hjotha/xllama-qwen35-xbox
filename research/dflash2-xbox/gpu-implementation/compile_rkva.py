"""Compile the RKVA (remote KVarN attention) shaders to AOT DXIL headers.

Each kernel is compiled with DXC (cs_6_0, -O3 -WX) and emitted as a C byte
array header under shaders/generated/, matching the DFlash convention so the
UWP engine can embed the DXIL and create PSOs without runtime compilation.

Usage (HPBEATS build host):
    python research/dflash2-xbox/gpu-implementation/compile_rkva.py
Set DXC to override the compiler path.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SHADER_DIR = ROOT / "shaders/rkva"
GEN_DIR = ROOT / "shaders/generated"

# (source, entry, header stem, symbol). Add entries as kernels land.
KERNELS = [
    # F16 bring-up / correctness path (also the KVarN materialize fallback).
    ("rkva_flash_attn.hlsl",  "CSFlashAttn", "rkva_flash_attn_dxil.h",  "kRkvaFlashAttnDxil"),
    ("rkva_store_f16.hlsl",   "CSStore",     "rkva_store_f16_dxil.h",   "kRkvaStoreF16Dxil"),
    # KVarN native path (lands with the bit-exact port; skipped until present).
    ("rkva_wht.hlsl",         "CSWht",         "rkva_wht_dxil.h",         "kRkvaWhtDxil"),
    ("rkva_store.hlsl",       "CSStore",       "rkva_store_dxil.h",       "kRkvaStoreDxil"),
    ("rkva_materialize.hlsl", "CSMaterialize", "rkva_materialize_dxil.h", "kRkvaMaterializeDxil"),
]


def compiler() -> str:
    explicit = os.environ.get("DXC")
    if explicit:
        return explicit
    found = shutil.which("dxc") or shutil.which("dxc.exe")
    if found:
        return found
    sdk = Path(r"C:\Program Files (x86)\Windows Kits\10\bin\10.0.26100.0\x64\dxc.exe")
    if sdk.is_file():
        return str(sdk)
    raise SystemExit("dxc not found; set DXC to the compiler path")


def emit(header: Path, symbol: str, source_name: str, entry: str, data: bytes) -> None:
    lines = [
        f"// AUTO-GENERATED by research/dflash2-xbox/gpu-implementation/compile_rkva.py; do not edit.",
        f"// Source: shaders/rkva/{source_name} (cs_6_0 {entry} -O3 -WX)",
        "#pragma once",
        "#include <cstddef>",
        "#include <cstdint>",
        f"// {len(data)} bytes DXIL",
        "// clang-format off",
        f"static const uint8_t {symbol}[] = {{",
    ]
    for index in range(0, len(data), 12):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[index:index + 12]) + ",")
    lines += ["};", f"static const size_t {symbol}Size = {len(data)};", "// clang-format on"]
    header.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{header}: {len(data)} bytes")


def main() -> None:
    GEN_DIR.mkdir(parents=True, exist_ok=True)
    dxc = compiler()
    compiled = 0
    for source_name, entry, header_name, symbol in KERNELS:
        source = SHADER_DIR / source_name
        if not source.is_file():
            print(f"skip {source_name} (not present yet)")
            continue
        with tempfile.TemporaryDirectory() as directory:
            dxil = Path(directory) / "kernel.dxil"
            subprocess.run(
                [dxc, "-T", "cs_6_0", "-E", entry, "-O3", "-WX", "-Fo", str(dxil), str(source)],
                check=True,
            )
            data = dxil.read_bytes()
        emit(GEN_DIR / header_name, symbol, source_name, entry, data)
        compiled += 1
    print(f"compiled {compiled} RKVA kernel(s)")


if __name__ == "__main__":
    main()
